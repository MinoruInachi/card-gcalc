import sys
sys.path.insert(0, "src")
from cardgcalc.calc.expr import Context, translate, CalcError
from cardgcalc.calc import numfmt

ctx = Context()
fails = 0
def t(src, want, angle="rad", cplx=False):
    global fails
    ctx.angle = angle; ctx.complex = cplx
    try:
        got = numfmt.fmt(ctx.evaluate(src))
    except CalcError as e:
        got = "ERR:" + str(e)
    ok = got == want
    if not ok:
        fails += 1
        try:
            code = translate(src)[0]
        except Exception as e:
            code = repr(e)
        print("FAIL", src, "->", got, "want", want, " code:", code)

