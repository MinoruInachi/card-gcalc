#!/usr/bin/env python3
"""Convert X11 misc-fixed BDF fonts (public domain) into card-gcalc font modules.

Each output module defines:
    W, H      glyph cell size in pixels
    BPR       bytes per glyph row (MONO_HLSB)
    GLYPHS    bytes: all glyph bitmaps, concatenated (H*BPR bytes per glyph)
    INDEX     str: the characters, in the same order as GLYPHS

Usage: tools/mkfont.py <font.bdf> <out.py> [charset-file]
"""
import sys

# Characters needed by card-gcalc (ASCII + math symbols used by the calculator).
EXTRA = (
    "πθ√∛∫∑Σ∏ΔαβγλμσφωΩ"  # greek / operators
    "²³¹⁰⁴⁵⁶⁷⁸⁹⁻ⁿˣ"  # superscripts
    "₀₁₂₃₄₅₆₇₈₉"  # subscripts
    "×÷±≤≥≠≈∞→←↑↓↵⇒∠°′·…▶◀▲▼■□●○✓"  # misc
    "ᴇ∂"
)


def parse_bdf(path):
    glyphs = {}
    fbb = None
    asc = desc = None
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        if line.startswith("FONTBOUNDINGBOX"):
            _, w, h, x, y = line.split()
            fbb = (int(w), int(h), int(x), int(y))
        elif line.startswith("FONT_ASCENT"):
            asc = int(line.split()[1])
        elif line.startswith("FONT_DESCENT"):
            desc = int(line.split()[1])
        elif line.startswith("STARTCHAR"):
            enc = None
            bbx = None
            rows = []
            for l2 in lines:
                if l2.startswith("ENCODING"):
                    enc = int(l2.split()[1])
                elif l2.startswith("BBX"):
                    _, w, h, x, y = l2.split()
                    bbx = (int(w), int(h), int(x), int(y))
                elif l2 == "BITMAP":
                    for l3 in lines:
                        if l3 == "ENDCHAR":
                            break
                        rows.append(int(l3, 16) if l3 else 0)
                    break
            glyphs[enc] = (bbx, rows)
    return fbb, asc, desc, glyphs


def render(fbb, asc, desc, bbx, rows):
    W = fbb[0]
    H = asc + desc
    bw, bh, bx, by = bbx
    nbytes = (bw + 7) // 8
    cell = [[0] * W for _ in range(H)]
    # baseline at row 'asc' from top; glyph top row = asc - (by + bh)
    top = asc - (by + bh)
    for r, val in enumerate(rows):
        for c in range(bw):
            if val & (1 << (nbytes * 8 - 1 - c)):
                yy = top + r
                xx = bx + c
                if 0 <= yy < H and 0 <= xx < W:
                    cell[yy][xx] = 1
    return cell


def main():
    src, out = sys.argv[1], sys.argv[2]
    fbb, asc, desc, glyphs = parse_bdf(src)
    W = fbb[0]
    H = asc + desc
    bpr = (W + 7) // 8
    chars = [chr(c) for c in range(32, 127)] + list(dict.fromkeys(EXTRA))
    data = bytearray()
    index = ""
    for ch in chars:
        g = glyphs.get(ord(ch))
        if g is None:
            print("missing", repr(ch), hex(ord(ch)), file=sys.stderr)
            continue
        cell = render(fbb, asc, desc, *g)
        for row in cell:
            for b in range(bpr):
                v = 0
                for bit in range(8):
                    x = b * 8 + bit
                    if x < W and row[x]:
                        v |= 0x80 >> bit
                data.append(v)
        index += ch
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Generated by tools/mkfont.py from %s\n" % src.split("/")[-1])
        f.write("# X11 misc-fixed font: public domain.\n")
        f.write("W = %d\nH = %d\nBPR = %d\n" % (W, H, bpr))
        f.write("INDEX = %r\n" % index)
        f.write("GLYPHS = (\n")
        step = H * bpr * 4
        for i in range(0, len(data), step):
            f.write("    %r\n" % bytes(data[i : i + step]))
        f.write(")\n")
    print("%s: %dx%d, %d glyphs, %d bytes" % (out, W, H, len(index), len(data)))


if __name__ == "__main__":
    main()
