#!/usr/bin/env python3
"""Convert the k8x12 Japanese bitmap font (BDF, Unicode) into a card-gcalc
font module that stays in flash when frozen.

Output module (src/nc/fonts/jp8x12.py):
    W, H   glyph cell (8 x 12)
    N      number of glyphs
    CODES  bytes: big-endian uint16 code points, sorted (binary search)
    GLYPHS bytes: H bytes per glyph (MONO_HLSB, 1 byte per row)

Only non-ASCII glyphs are included (ASCII comes from the Latin fonts).

k8x12 (C) Num Kadoma -- "These fonts are free software.  Unlimited
permission is granted to use, copy, and distribute them, with or without
modification, either commercially or noncommercially."
https://littlelimit.net/k8x12.htm

Usage: tools/mkfont_jp.py k8x12L.bdf src/nc/fonts/jp8x12.py
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from mkfont import parse_bdf, render  # noqa: E402


def main():
    src, out = sys.argv[1], sys.argv[2]
    fbb, asc, desc, glyphs = parse_bdf(src)
    W = fbb[0]
    H = asc + desc
    assert W == 8
    codes = bytearray()
    data = bytearray()
    n = 0
    for cp in sorted(glyphs):
        if cp < 0x80 or cp > 0xFFFF:
            continue
        cell = render(fbb, asc, desc, *glyphs[cp])
        for row in cell:
            v = 0
            for x in range(8):
                if row[x]:
                    v |= 0x80 >> x
            data.append(v)
        codes += bytes((cp >> 8, cp & 0xFF))
        n += 1
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Generated by tools/mkfont_jp.py from %s\n" % src.split("/")[-1])
        f.write("# k8x12 (C) Num Kadoma: free software, unlimited permission to use,\n")
        f.write("# copy and distribute, with or without modification.\n")
        f.write("W = %d\nH = %d\nN = %d\n" % (W, H, n))
        f.write("CODES = (\n")
        for i in range(0, len(codes), 64):
            f.write("    %r\n" % bytes(codes[i : i + 64]))
        f.write(")\nGLYPHS = (\n")
        for i in range(0, len(data), 96):
            f.write("    %r\n" % bytes(data[i : i + 96]))
        f.write(")\n")
    print("%s: %d glyphs, %d bytes" % (out, n, len(data) + len(codes)))


if __name__ == "__main__":
    main()
