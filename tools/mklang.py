#!/usr/bin/env python3
"""Merge lang/*.tsv (English<TAB>Japanese per line, '#' comments, '\\n' for
newline) into src/nc/lang_ja.py (sorted constant tuples for bisection)."""
import glob
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def main():
    table = {}
    src_of = {}
    bad = 0
    for path in sorted(glob.glob(os.path.join(ROOT, "lang", "*.tsv"))):
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as f:
            for n, line in enumerate(f, 1):
                line = line.rstrip("\n")
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                if "\t" not in line:
                    print("%s:%d: no TAB" % (name, n), file=sys.stderr)
                    bad += 1
                    continue
                en, ja = line.split("\t", 1)
                en = en.replace("\\n", "\n")
                ja = ja.strip().replace("\\n", "\n")
                if en in table and table[en] != ja:
                    print("%s:%d: conflict for %r: %r (%s) vs %r" % (name, n, en, table[en], src_of[en], ja),
                          file=sys.stderr)
                    bad += 1
                    continue
                if en.count("%") != ja.count("%"):
                    print("%s:%d: format mismatch %r -> %r" % (name, n, en, ja), file=sys.stderr)
                    bad += 1
                table[en] = ja
                src_of[en] = name
    keys = sorted(table)
    out = os.path.join(ROOT, "src", "nc", "lang_ja.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Generated by tools/mklang.py from lang/*.tsv -- do not edit.\n")
        f.write("KEYS = (\n")
        for k in keys:
            f.write("    %r,\n" % k)
        f.write(")\nVALS = (\n")
        for k in keys:
            f.write("    %r,\n" % table[k])
        f.write(")\n")
    print("%s: %d strings" % (os.path.relpath(out, ROOT), len(keys)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
